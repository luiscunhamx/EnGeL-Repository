"""Runs before every `quarto render`. Generates, from the protocols' YAML headers:
  register.qmd                 the protocol register (written + planned protocols)
  bench/<ID>-bench.qmd         one bench sheet per protocol (steps from the Procedure section)
  to-confirm.qmd / .csv        every [TO CONFIRM] still open, per protocol and shared include
  people.qmd                   people (data/people.yml) with the protocols they wrote or contributed to
  _area-cards.qmd              cards per area for the home page (included by index.qmd)
  _quarto.yml (sidebar block)  sidebar with short titles, in workflow order (SIDEBAR_ORDER)
Generated files are overwritten every time: edit the protocol, never these files."""
import os, re, glob, yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

def read_qmd(path):
    text = open(path, encoding='utf-8').read()
    m = re.match(r'^---\n(.*?)\n---\n(.*)$', text, re.S)
    return (yaml.safe_load(m.group(1)), m.group(2)) if m else ({}, text)

def resolve_includes(body, base):
    def rep(m):
        p = os.path.normpath(os.path.join(base, m.group(1)))
        return resolve_includes(open(p, encoding='utf-8').read(), os.path.dirname(p))
    return re.sub(r'\{\{<\s*include\s+(\S+)\s*>\}\}', rep, body)

def section(body, name):
    m = re.search(r'^## ' + re.escape(name) + r'\s*$(.*?)(?=^## |\Z)', body, re.S | re.M)
    return m.group(1) if m else ''

def protocols():
    out = []
    for p in sorted(glob.glob('protocols/**/*.qmd', recursive=True)):
        meta, body = read_qmd(p)
        if meta.get('protocol-id'):
            out.append((p, meta, resolve_includes(body, os.path.dirname(p))))
    return out

def esc(s): return str(s).replace('|', '\\|')

def register(protos):
    rows = ['| ID | Title | Version | Status | Date | Area |', '|:--|:--|:--|:--|:--|:--|']
    for p, m, _ in protos:
        rows.append(f"| [{m['protocol-id']}]({p}) | {esc(m.get('title',''))} | {m.get('version','')} | {m.get('status','')} | {m.get('date','')} | {esc(m.get('area',''))} |")
    planned = yaml.safe_load(open('data/planned.yml', encoding='utf-8')) or []
    prow = ['| ID | Title | Notes |', '|:--|:--|:--|'] + [f"| {x['id']} | {esc(x['title'])} | {esc(x.get('notes',''))} |" for x in planned]
    txt = ('---\ntitle: "Protocol register"\n---\n\n<!-- Generated by tools/prerender.py from the protocols\' YAML headers and data/planned.yml. Do not edit. -->\n\n'
           '## Protocols\n\n' + '\n'.join(rows) + '\n\n## Planned\n\n' + '\n'.join(prow) + '\n')
    write('register.qmd', txt)

def bench(path, meta, body):
    pid = meta['protocol-id']
    proc = section(body, 'Procedure')
    prep = section(body, 'Reagent preparation')
    lines = proc.split('\n')
    out, n, rows = [], 0, []
    def flush():
        nonlocal rows
        if rows:
            out.append('| ☐ | No. | Step |\n|:--|:--|:' + '-' * 70 + '|\n' + '\n'.join(rows) + '\n')
            rows = []
    i = 0
    while i < len(lines):
        l = lines[i]
        if l.startswith('### ') or re.match(r'^\*\*[A-Z]\. .*\*\*$', l):
            flush(); out.append(('#### ' + l[4:]) if l.startswith('### ') else l); out.append('')
        elif l.startswith('(@)'):
            n += 1; txt = l[3:].strip(); j = i + 1
            while j < len(lines) and lines[j].startswith('    - '):
                txt += ' · ' + lines[j][6:].strip(); j += 1
            rows.append(f'| ☐ | {n} | {esc(txt)} |'); i = j; continue
        elif l.startswith('::: {.callout-important'):
            j = i + 1; txt = []
            while j < len(lines) and not lines[j].startswith(':::'):
                txt.append(lines[j].strip()); j += 1
            rows.append(f"| **!** | | **CRITICAL** {esc(' '.join(t for t in txt if t))} |"); i = j + 1; continue
        elif l.startswith('|') and rows == [] and out and not out[-1].startswith('|'):
            pass
        elif l.startswith('|'):
            flush(); tbl = []
            while i < len(lines) and lines[i].startswith('|'):
                tbl.append(lines[i]); i += 1
            out.append('\n'.join(tbl) + '\n'); continue
        elif l.startswith('- '):
            rows.append(f'| ☐ | • | {esc(l[2:].strip())} |')
        elif re.match(r'^\[TO CONFIRM', l.strip()):
            flush(); out.append(l.strip() + '\n')
        i += 1
    flush()
    # tables marked <!-- bench --> in Reagent preparation
    extra = []
    for m in re.finditer(r'<!-- bench -->\n(.*?)\n\n(\|.*?)(?:\n\n|\Z)', body, re.S):
        extra.append(m.group(1).strip() + '\n\n' + m.group(2).strip() + '\n')
    lots = meta.get('bench-lots', [])
    head = ['| | |', '|:' + '-' * 30 + '|:' + '-' * 45 + '|', '| Date | |', '| Operator | |', '| Plate ID / samples | |'] + [f'| {esc(x)} | |' for x in lots]
    txt = (f'---\ntitle: "Bench sheet · {pid}"\nprotocol-id: {pid}\nshort-title: "Bench sheet"\nversion: "{meta.get("version","")}"\n---\n\n'
           f'<!-- Generated by tools/prerender.py from {path}. Do not edit: change the protocol instead. -->\n\n'
           f'**{meta.get("title","")}** · version {meta.get("version","")} ({meta.get("date","")}). Full protocol: [{pid}](../{path[:-4]}.html). '
           'Tick each step when done; write deviations in Notes.\n\n'
           + '\n'.join(head) + '\n\n' + '\n'.join(extra) + '\n' + '\n'.join(out)
           + '\n\n**Notes / deviations**\n\n|  |\n|:' + '-' * 100 + '|\n' + '|   |\n|   |\n|   |\n')
    write(f'bench/{pid}-bench.qmd', txt)

TC = re.compile(r'\[TO CONFIRM(?::\s*([^\]]*))?\]')

def scan_tc(path):
    """[TO CONFIRM] marks in one file, outside its Open questions section: (section, line, what, context)."""
    found, sec, inyaml = [], 'Header', False
    for i, l in enumerate(open(path, encoding='utf-8').read().split('\n')):
        if i == 0 and l == '---': inyaml = True; continue
        if inyaml:
            if l == '---': inyaml = False
            for m in TC.finditer(l): found.append(('YAML header', i + 1, (m.group(1) or '').strip(), l.strip()))
            continue
        if l.startswith('## '): sec = re.sub(r'\s*\{.*\}$', '', l[3:]).strip()
        if sec.startswith('Open questions'): continue
        for m in TC.finditer(l): found.append((sec, i + 1, (m.group(1) or '').strip(), l.strip()))
    return found

def to_confirm(protos):
    import csv, io
    def ctx(c):
        c = TC.sub('', re.sub(r'^\(@\)\s*|^[-*]\s*|^\d+\.\s*', '', c))
        c = re.sub(r'!\[([^\]]*)\]\([^)]*\)(\{[^}]*\})?', r'Figure: \1', c)   # images -> caption text
        c = re.sub(r'\[([^\]]*)\]\([^)]*\)(\{[^}]*\})?', r'\1', c)           # links -> text
        c = re.sub(r'\{[#.][^}]*\}|<[^>]+>|\{\{<[^>]*>\}\}', '', c)              # attributes, html, shortcodes
        c = re.sub(r'[`*|]', '', re.sub(r'\s+', ' ', c)).strip()
        return (c[:140] + '…') if len(c) > 140 else c
    allrows, parts = [], []
    summary = ['| Protocol | Status | Open values |', '|:--|:--|--:|']
    sources = [(m['protocol-id'], p, m.get('status', ''), m.get('version', '')) for p, m, _ in protos]
    sources += [(os.path.basename(f), f, 'include', '') for f in sorted(glob.glob('includes/_*.qmd'))]
    sources += [('workflows/' + os.path.basename(f), f, 'workflow page', '') for f in sorted(glob.glob('workflows/*.qmd'))]
    for pid, path, status, ver in sources:
        found = scan_tc(path)
        if not found: continue
        link = f'[{pid}]({path})' if path.startswith('protocols') else f'`{pid}`'
        summary.append(f'| {link} | {status} | {len(found)} |')
        rows = ['| Section | Line | What to confirm | Context |', '|:--|--:|:--|:--|']
        for sec, ln, what, c in found:
            rows.append(f'| {esc(sec)} | {ln} | {esc(what) or "—"} | {esc(ctx(c))} |')
            allrows.append([pid, ver, sec, ln, what, ctx(c)])
        parts.append(f'## {pid} ({len(found)})\n\n' + '\n'.join(rows) + '\n')
    buf = io.StringIO(); w = csv.writer(buf)
    w.writerow(['Protocol', 'Version', 'Section', 'Line', 'What to confirm', 'Context']); w.writerows(allrows)
    write('to-confirm.csv', buf.getvalue())
    txt = ('---\ntitle: "Values to confirm"\nsubtitle: "Open [TO CONFIRM] values in the drafts"\ntoc: true\n---\n\n'
           '<!-- Generated by tools/prerender.py. Do not edit. -->\n\n'
           f'**{len(allrows)} values** are still marked [TO CONFIRM]. A protocol can be released only when its list is empty. '
           'Line numbers refer to the protocol source file (*Edit this page*). Download the list as a table: [to-confirm.csv](to-confirm.csv).\n\n'
           + '\n'.join(summary) + '\n\n' + '\n'.join(parts))
    write('to-confirm.qmd', txt)

AREAS = [  # (folder, card title, Bootstrap icon, one-line description)
    ('fauna', 'Fauna sample processing', 'bug', 'Field sampling, extraction and sorting of soil animals.'),
    ('molb', 'Molecular biology', 'droplet-half', 'Nucleic acid extraction, quality control, PCR and sequencing libraries.'),
    ('bioinf', 'Bioinformatics', 'diagram-3', 'From raw reads to taxonomic tables.'),
]

def area_cards(protos):
    out = ['::: {.grid .engel-cards}']
    for folder, title, icon, desc in AREAS:
        items = [(p, m) for p, m, _ in protos if p.split('/')[1] == folder]
        first = items[0][0] if items else 'register.qmd'
        n = len(items)
        out.append(f'::: {{.g-col-12 .g-col-md-4 .engel-card}}\n'
                   f'`<i class="bi bi-{icon} engel-card-icon" aria-hidden="true"></i>`{{=html}}\n\n'
                   f'**[{title}]({first})**\n\n{desc}\n\n'
                   f'[{n} protocol{"s" if n != 1 else ""}]{{.engel-card-count}}\n:::')
    out.append(':::')
    write('_area-cards.qmd', '<!-- Generated by tools/prerender.py. Do not edit. -->\n\n' + '\n\n'.join(out) + '\n')

def people(protos):
    ppl = yaml.safe_load(open('data/people.yml', encoding='utf-8')) or []
    blocks = []
    for person in ppl:
        name = person['name']
        roles = []
        for p, m, _ in protos:
            authors = [a.get('name', '') if isinstance(a, dict) else str(a) for a in (m.get('author') or [])]
            contribs = [str(c) for c in (m.get('contributors') or [])]
            if name in authors: roles.append((m['protocol-id'], p, 'author'))
            elif any(c.startswith(name) for c in contribs): roles.append((m['protocol-id'], p, 'contributor'))
        line = f'### {name}\n\n'
        meta = []
        if person.get('role'): meta.append(person['role'])
        meta.append(person.get('affiliation') or 'EnGeL-UC, Centre for Functional Ecology, University of Coimbra')
        if person.get('orcid'): meta.append(f'ORCID [{person["orcid"]}](https://orcid.org/{person["orcid"]})')
        line += ' · '.join(meta) + '\n\n'
        if person.get('bio'): line += person['bio'].strip() + '\n\n'
        if roles:
            line += '**Protocols:** ' + '; '.join(f'[{pid}]({p}) ({r})' for pid, p, r in roles) + '\n'
        blocks.append(line)
    txt = ('---\ntitle: "People"\nsubtitle: "Authors and contributors of the EnGeL-UC protocols"\n---\n\n'
           '<!-- Generated by tools/prerender.py from data/people.yml and the protocols. Do not edit. -->\n\n'
           'Authors wrote the protocol and are cited in its *How to cite* line; contributors provided sections, methods or review. '
           'To get in touch, use the lab contact on each protocol page.\n\n' + '\n'.join(blocks))
    write('people.qmd', txt)

# Order of protocols in the sidebar (workflow order); protocols not listed follow alphabetically.
SIDEBAR_ORDER = ['EnGeL-FAUNA-MAR-MORPH', 'EnGeL-MOLB-DNA-MAG', 'EnGeL-MOLB-DNA-COL', 'EnGeL-MOLB-DNA-BARC',
                 'EnGeL-MOLB-DNA-BEE', 'EnGeL-MOLB-RNA', 'EnGeL-MOLB-NAQC', 'EnGeL-MOLB-MB', 'EnGeL-MOLB-KAPA',
                 'EnGeL-BIOINF-OBITOOLS4']

def sidebar(protos):
    def key(x):
        pid = x[1]['protocol-id']
        return (SIDEBAR_ORDER.index(pid) if pid in SIDEBAR_ORDER else len(SIDEBAR_ORDER), pid)
    def q(t): return '"' + str(t).replace('"', '\\"') + '"'
    L = ['      - href: index.qmd', '        text: Home', '      - register.qmd', '      - to-confirm.qmd', '      - people.qmd']
    for folder, title, _, _ in AREAS:
        items = sorted([(p, m) for p, m, _ in protos if p.split('/')[1] == folder], key=key)
        if not items: continue
        L.append(f'      - section: {q(title)}'); L.append('        contents:')
        for p, m in items:
            L += [f'          - href: {p}', f'            text: {q(m.get("short-title") or m["title"])}']
    L += ['      - section: "Workflows"', '        contents:']
    wf_first = ['workflows/soil-fauna-metabarcoding.qmd', 'workflows/sequencing-submission.qmd']
    wfs = [w for w in wf_first if os.path.exists(w)] + sorted(w for w in glob.glob('workflows/*.qmd') if w not in wf_first)
    L += [f'          - {w}' for w in wfs]
    L += ['      - section: "Bench sheets"', '        contents:']
    for p, m in sorted([(p, m) for p, m, _ in protos], key=key):
        pid = m['protocol-id']
        L += [f'          - href: bench/{pid}-bench.qmd', f'            text: {q(pid.replace("EnGeL-", ""))}']
    cfg = open('_quarto.yml', encoding='utf-8').read()
    a = cfg.index('      # BEGIN sidebar'); a = cfg.index('\n', a) + 1
    b = cfg.index('      # END sidebar')
    new = cfg[:a] + '\n'.join(L) + '\n' + cfg[b:]
    if new != cfg:
        write('_quarto.yml', new)
        print('prerender: sidebar updated in _quarto.yml (takes effect on the next render)')

def write(path, txt):
    old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
    if old != txt:
        open(path, 'w', encoding='utf-8').write(txt)

if __name__ == '__main__':
    ps = protocols()
    register(ps)
    to_confirm(ps)
    area_cards(ps)
    people(ps)
    sidebar(ps)
    for p, m, b in ps:
        bench(p, m, b)
    print(f'prerender: {len(ps)} protocol(s); register and bench sheets updated')
