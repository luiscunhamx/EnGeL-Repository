"""Runs before every `quarto render`. Generates, from the protocols' YAML headers:
  register.qmd                 the protocol register (written + planned protocols)
  bench/<ID>-bench.qmd         one bench sheet per protocol (steps from the Procedure section)
Generated files are overwritten every time: edit the protocol, never these files."""
import os, re, glob, yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

def read_qmd(path):
    text = open(path, encoding='utf-8').read()
    m = re.match(r'^---\n(.*?)\n---\n(.*)$', text, re.S)
    return (yaml.safe_load(m.group(1)), m.group(2)) if m else ({}, text)

def resolve_includes(body, base):
    def rep(m):
        p = os.path.normpath(os.path.join(base, m.group(1)))
        return resolve_includes(open(p, encoding='utf-8').read(), os.path.dirname(p))
    return re.sub(r'\{\{<\s*include\s+(\S+)\s*>\}\}', rep, body)

def section(body, name):
    m = re.search(r'^## ' + re.escape(name) + r'\s*$(.*?)(?=^## |\Z)', body, re.S | re.M)
    return m.group(1) if m else ''

def protocols():
    out = []
    for p in sorted(glob.glob('protocols/**/*.qmd', recursive=True)):
        meta, body = read_qmd(p)
        if meta.get('protocol-id'):
            out.append((p, meta, resolve_includes(body, os.path.dirname(p))))
    return out

def esc(s): return str(s).replace('|', '\\|')

def register(protos):
    rows = ['| ID | Title | Version | Status | Date | Area |', '|:--|:--|:--|:--|:--|:--|']
    for p, m, _ in protos:
        rows.append(f"| [{m['protocol-id']}]({p}) | {esc(m.get('title',''))} | {m.get('version','')} | {m.get('status','')} | {m.get('date','')} | {esc(m.get('area',''))} |")
    planned = yaml.safe_load(open('data/planned.yml', encoding='utf-8')) or []
    prow = ['| ID | Title | Notes |', '|:--|:--|:--|'] + [f"| {x['id']} | {esc(x['title'])} | {esc(x.get('notes',''))} |" for x in planned]
    txt = ('---\ntitle: "Protocol register"\n---\n\n<!-- Generated by tools/prerender.py from the protocols\' YAML headers and data/planned.yml. Do not edit. -->\n\n'
           '## Protocols\n\n' + '\n'.join(rows) + '\n\n## Planned\n\n' + '\n'.join(prow) + '\n')
    write('register.qmd', txt)

def bench(path, meta, body):
    pid = meta['protocol-id']
    proc = section(body, 'Procedure')
    prep = section(body, 'Reagent preparation')
    lines = proc.split('\n')
    out, n, rows = [], 0, []
    def flush():
        nonlocal rows
        if rows:
            out.append('| ☐ | No. | Step |\n|:--|:--|:' + '-' * 70 + '|\n' + '\n'.join(rows) + '\n')
            rows = []
    i = 0
    while i < len(lines):
        l = lines[i]
        if l.startswith('### ') or re.match(r'^\*\*[A-Z]\. .*\*\*$', l):
            flush(); out.append(('#### ' + l[4:]) if l.startswith('### ') else l); out.append('')
        elif l.startswith('(@)'):
            n += 1; txt = l[3:].strip(); j = i + 1
            while j < len(lines) and lines[j].startswith('    - '):
                txt += ' · ' + lines[j][6:].strip(); j += 1
            rows.append(f'| ☐ | {n} | {esc(txt)} |'); i = j; continue
        elif l.startswith('::: {.callout-important'):
            j = i + 1; txt = []
            while j < len(lines) and not lines[j].startswith(':::'):
                txt.append(lines[j].strip()); j += 1
            rows.append(f"| **!** | | **CRITICAL** {esc(' '.join(t for t in txt if t))} |"); i = j + 1; continue
        elif l.startswith('|') and rows == [] and out and not out[-1].startswith('|'):
            pass
        elif l.startswith('|'):
            flush(); tbl = []
            while i < len(lines) and lines[i].startswith('|'):
                tbl.append(lines[i]); i += 1
            out.append('\n'.join(tbl) + '\n'); continue
        elif l.startswith('- '):
            rows.append(f'| ☐ | • | {esc(l[2:].strip())} |')
        elif re.match(r'^\[TO CONFIRM', l.strip()):
            flush(); out.append(l.strip() + '\n')
        i += 1
    flush()
    # tables marked <!-- bench --> in Reagent preparation
    extra = []
    for m in re.finditer(r'<!-- bench -->\n(.*?)\n\n(\|.*?)(?:\n\n|\Z)', body, re.S):
        extra.append(m.group(1).strip() + '\n\n' + m.group(2).strip() + '\n')
    lots = meta.get('bench-lots', [])
    head = ['| | |', '|:' + '-' * 30 + '|:' + '-' * 45 + '|', '| Date | |', '| Operator | |', '| Plate ID / samples | |'] + [f'| {esc(x)} | |' for x in lots]
    txt = (f'---\ntitle: "Bench sheet · {pid}"\nprotocol-id: {pid}\nshort-title: "Bench sheet"\nversion: "{meta.get("version","")}"\n---\n\n'
           f'<!-- Generated by tools/prerender.py from {path}. Do not edit: change the protocol instead. -->\n\n'
           f'**{meta.get("title","")}** · version {meta.get("version","")} ({meta.get("date","")}). Full protocol: [{pid}](../{path[:-4]}.html). '
           'Tick each step when done; write deviations in Notes.\n\n'
           + '\n'.join(head) + '\n\n' + '\n'.join(extra) + '\n' + '\n'.join(out)
           + '\n\n**Notes / deviations**\n\n|  |\n|:' + '-' * 100 + '|\n' + '|   |\n|   |\n|   |\n')
    write(f'bench/{pid}-bench.qmd', txt)

def write(path, txt):
    old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
    if old != txt:
        open(path, 'w', encoding='utf-8').write(txt)

if __name__ == '__main__':
    ps = protocols()
    register(ps)
    for p, m, b in ps:
        bench(p, m, b)
    print(f'prerender: {len(ps)} protocol(s); register and bench sheets updated')
